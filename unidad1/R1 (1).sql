-- REQUERIMIENTO 1
DECLARE -- INICIO ZONA DECLARATIVA
/* SE DECLARAN LAS VARIABLES PARA ALMACENAR EL SALARIO MÁXIMO, EL SALARIO
PROMEDIO, EL MENOR SALARIO Y LA SUMA DE SALARIOS. LOS TIPOS DE DATOS SERÁN 
LOS MISMOS QUE LOS CAMPOS DE LA TABLA EMPLOYEES. EL CAMPO CANT_EMP (QUE 
ALMACENARÁ LA CANTIDAD DE EMPLEADOS) ES DE TIPO NUMBER TAMAÑO 3 CIFRAS */
v_sal_max employees.salary%TYPE; 
v_sal_prom employees.salary%TYPE;
v_sal_min employees.salary%TYPE;
v_sal_total employees.salary%TYPE;
v_cant_emp  NUMBER(3):=0;
BEGIN -- INICIO ZONA EJECUTABLE
/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL MÁXIMO SUELDO (FUNCIÓN MAX), 
EL SALARIO PROMEDIO (FUNCIÓN AVG), EL SALARIO MÍNIMO (FUNCIÓN MIN), LA SUMA 
DE LOS SALARIOS (FUNCIÓN SUM) Y LA CANTIDAD DE EMPLEADOS (FUNCIÓN COUNT) DE LA 
TABLA EMPLOYEES Y SE ALMACENAN EN LAS RESPECTIVAS VARIABLES, PREVIAMENTE
DECLARADAS (CLÁUSULA INTO)*/
SELECT MAX(salary), AVG(salary), MIN(salary), SUM(salary),COUNT(employee_id)
INTO v_sal_max, v_sal_prom, v_sal_min, v_sal_total, v_cant_emp
FROM EMPLOYEES;
-- SE IMPRIMEN CADA UNA DE LAS VARIBLES, DE ACUERDO AL FORMATO DE LA IMAGEN
DBMS_OUTPUT.PUT_LINE('INFORME DE LA EMPRESA            '|| SYSDATE); 
DBMS_OUTPUT.PUT_LINE('-------------------------------------------');
DBMS_OUTPUT.PUT_LINE('Salario Máximo          Salario Promedio       Salario Mínimo              Salario Total');
DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------------------------');
DBMS_OUTPUT.PUT_LINE(TO_CHAR(v_sal_max, '$999,000')||'                '||TO_CHAR(v_sal_prom, '$999,000')||'               '||TO_CHAR(v_sal_min, '$999,000')||'                   '||TO_CHAR(v_sal_total, '$999,000'));
DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------------------------');
DBMS_OUTPUT.PUT_LINE('Los valores calculados están efectuados sobre '||v_cant_emp||' empleados');
END; -- FINALIZACIÓN DEL BLOQUE


-- REQUERIMIENTO 2
DECLARE -- INICIO ZONA DECLARATIVA
/* SE DECLARAN LAS VARIABLES PARA ALMACENAR EL NOMBRE Y LA CANTIDAD DE EMPLEADOS 
PARA LOS DEPARTAMENTOS CON MAYOR Y MENOR CANTIDAD DE EMPLEADOS DE LA EMPRESA. 
LOS NOMBRES DE DEPARTAMENTOS SERÁN DEL MISMO TIPO DE DATOS QUE EL CAMPO 
DEPARTMENT_NAME DE LA TABLA DEPARTMENTS. LAS CANTIDADES DE EMPLEADOS SERÁN
DE TIPO NUMÉRICO DE TAMAÑO 2 CIFRAS E INICIALIZADAS EN CERO */
v_nom_depto_max departments.department_name%TYPE;
v_cant_depto_max NUMBER(2):=0;
v_nom_depto_min departments.department_name%TYPE;
v_cant_depto_min NUMBER(2):=0;

BEGIN -- INICIO ZONA EJECUTABLE
/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL NOMBRE DEL DEPARTAMENTO
Y LA CANTIDAD DE EMPLEADOS DONDE DEL DEPARTAMENTO CON MAYOR CANTIDAD DE EMPLEADOS,
OBTENIDOS DE LA SUBCONSULTA Y SE ALMACENAN EN LAS RESPECTIVAS VARIABLES, PREVIAMENTE
DECLARADAS (CLÁUSULA INTO)*/
SELECT department_name, COUNT(employee_id)
INTO v_nom_depto_max, v_cant_depto_max
FROM departments d JOIN employees e
ON d.department_id = e.department_id
GROUP BY department_name
HAVING COUNT(employee_id) = (SELECT MAX(COUNT(EMPLOYEE_ID))
                             FROM EMPLOYEES
                             GROUP BY DEPARTMENT_ID);
                             
/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL NOMBRE DEL DEPARTAMENTO
Y LA CANTIDAD DE EMPLEADOS DONDE DEL DEPARTAMENTO CON MENOR CANTIDAD DE EMPLEADOS,
OBTENIDOS DE LA SUBCONSULTA. EN ESTE CASO, COMO EXISTEN VARIOS DEPARTAMENTOS CON LA 
MENOR CANTIDAD DE EMPLEADOS, ES DECIR, UN EMPLEADO, SE ESTÁ CONSIDERANDO EL PRIMERO
DE LA LISTA (CON LA INSTRUCCIÓN ROWNUM = 1)
Y SE ALMACENAN EN LAS RESPECTIVAS VARIABLES, PREVIAMENTE DECLARADAS (CLÁUSULA INTO)*/                             
SELECT department_name, COUNT(employee_id)
INTO v_nom_depto_min, v_cant_depto_min
FROM departments d JOIN employees e
ON d.department_id = e.department_id
WHERE ROWNUM = 1
GROUP BY department_name
HAVING COUNT(employee_id) = (SELECT MIN(COUNT(EMPLOYEE_ID))
                             FROM EMPLOYEES
                             GROUP BY DEPARTMENT_ID);

-- SE IMPRIMEN LAS VARIABLES, DE ACUERDO AL FORMATO ESPECIFICADO                             
DBMS_OUTPUT.PUT_LINE('INFORME PARA REDISTRIBUIR EMPLEADOS');
DBMS_OUTPUT.PUT_LINE('-------------------------------------------');
DBMS_OUTPUT.PUT_LINE('DEPARTAMENTO          TOTAL EMPLEADOS');
DBMS_OUTPUT.PUT_LINE('-------------------------------------------');
DBMS_OUTPUT.PUT_LINE(v_nom_depto_min||'                '||v_cant_depto_min);
DBMS_OUTPUT.PUT_LINE(v_nom_depto_max||'                      '||v_cant_depto_max);
END; -- FINALIZACIÓN DEL BLOQUE

-- REQUERIMIENTO 3
DECLARE -- INICIO ZONA DECLARATIVA
/* SE DECLARAN LAS VARIABLES PARA ALMACENAR EL ID DEL JEFE, NOMBRE DEL JEFE, 
APELLIDO DEL JEFE, CANTIDAD DE EMPLEADOS A CARGO Y ASIGNACIÓN DE DINERO QUE LE
CORRESPONDE AL EMPLEADO QUE ES JEFE CON LA MAYOR CANTIDAD DE EMPLEADOS A CARGO.
LOS CAMPOS ID, NOMBRE, APELLIDO TENDRÁN LOS MISMOS TIPOS DE DATOS QUE LOS CAMPOS 
EMPLOYEE_ID, FIRST_NAME Y LAST_NAME DE LA TABLA EMPLOYEES. LOS CAMPOS CANT_EMP
Y ASIGNACIÓN SERÁN DE TIPO NUMÉRICO DE TAMAÑOS 3 Y 6 CIFRAS, RESPECTIVAMENTE */
v_id_jefe employees.employee_id%TYPE;
v_nom_jefe employees.first_name%TYPE;
v_apell_jefe employees.last_name%TYPE;
v_cant_emp NUMBER(3);
v_asignacion NUMBER(6);

BEGIN -- INICIO ZONA EJECUTABLE
/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL ID, NOMBRE Y APELLIDO DEL EMPLEADO 
QUE ES JEFE, ADEMÁS DE LA CANTIDAD DE EMPLEADOS A CARGO Y EL VALOR DE ASIGNACIÓN 
QUE ES 1000 POR CADA EMPLEADO QUE TIENE A CARGO, DE AQUEL JEFE CON LA MAYOR 
CANTIDAD DE EMPLEADOS A CARGO (OBTENIDO DE LA SUBCONSULTA) Y SE ALMACENAN EN 
LAS RESPECTIVAS VARIABLES,PREVIAMENTE DECLARADAS (CLÁUSULA INTO)*/  
SELECT e.manager_id, emp.first_name, emp.last_name, COUNT(e.employee_id), 
COUNT(e.employee_id)*1000
INTO v_id_jefe, v_nom_jefe, v_apell_jefe, v_cant_emp, v_asignacion
FROM employees e JOIN employees emp
ON e.manager_id = emp.employee_id
GROUP BY  e.manager_id, emp.first_name, emp.last_name
HAVING COUNT (e.employee_id) = (SELECT MAX(COUNT(employee_id))
                                FROM employees
                                GROUP BY manager_id);

-- SE IMPRIMEN LAS VARIABLES, DE ACUERDO AL FORMATO ESPECIFICADO  
DBMS_OUTPUT.PUT_LINE('INFORME PAGO ASIGNACIÓN JEFE CON MÁS EMPLEADOS');
DBMS_OUTPUT.PUT_LINE('----------------------------------------------');
DBMS_OUTPUT.PUT_LINE('ID. JEFE:   '||v_id_jefe||'    '||'NOMBRE: '||v_nom_jefe||' '||v_apell_jefe);
DBMS_OUTPUT.PUT_LINE('EMPLEADOS A SU CARGO               VALOR ASIGNACIÓN');
DBMS_OUTPUT.PUT_LINE('---------------------------------------------------');
DBMS_OUTPUT.PUT_LINE('              '||v_cant_emp||'                         '||TO_CHAR(v_asignacion, '$99,000'));
END; -- FINALIZACIÓN DEL BLOQUE

-- REQUERIMIENTO 4
DECLARE -- INICIO ZONA DECLARATIVA
/* SE DECLARAN LAS VARIABLES PARA ALMACENAR EL SALARIO PROMEDIO, EL ID DEL EMPLEADO,
NOMBRE DEL EMPLEADO, APELLIDO DEL EMPLEADO, SUELDO DEL EMPLEADO, Y CARGO DEL EMPLEADO
QUE SE EVALUARÁ SI POSEE UN SUELDO SUPERIOR, IGUAL O INFERIOR AL PROMEDIO. 
LAS VARIABLES TENDRÁN LOS MISMOS TIPOS DE DATOS QUE LOS CAMPOS DE LAS RESPECTIVAS
TABLAS QUE SE ESTÁN CONSULTANDO. LA VARIABLE EMP_ID SERÁ INICIALIZADA CON EL VALOR 150,
PARA REALIZAR LA PRUEBA AL BLOQUE ANÓNIMO */
v_sal_prom employees.salary%TYPE;
v_emp_id employees.employee_id%TYPE := 150;
v_emp_nom employees.first_name%TYPE;
v_emp_ape employees.last_name%TYPE;
v_emp_salary employees.salary%TYPE;
v_emp_job jobs.job_title%TYPE;
BEGIN -- INICIO ZONA EJECUTABLE
/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL SUELDO PROMEDIO ENTRE TODOS LOS
EMPLEADOS DE LA TABLA EMPLOYEES Y SE ALMACENA EN SU RESPECTIVA VARIABLE, 
PREVIAMENTE DECLARADA (CLÁUSULA INTO)*/  
    SELECT AVG(salary)
    INTO v_sal_prom
    FROM employees;

/* A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL ID DEL EMPLEADO, NOMBRE DEL 
EMPLEADO, APELLIDO DEL EMPLEADO Y NOMBRE DEL CARGO DEL EMPLEADO, CUYO ID ES EL MISMO
DE LA VARIBALE EMP_ID, ES DECIR, EL EMPLEADO ID 150 Y SE ALMACENAN EN LAS RESPECTIVAS
VARIABLES, PREVIAMENTE DECLARADAS (CLÁUSULA INTO)*/  
    SELECT e.employee_id, e.first_name, e.last_name, e.salary, j.job_title
    INTO v_emp_id, v_emp_nom, v_emp_ape, v_emp_salary, v_emp_job
    FROM employees e JOIN jobs j
    ON e.job_id = j.job_id
    WHERE employee_id = v_emp_id;
/* A TRAVÉS DEL IF, SE PREGUNTA SI EL SALARIO DEL EMPLEADO ES MENOR AL PROMEDIO, 
SI ES ASÍ, IMPRIME EL MENSAJE DE ACUERDO AL FORMATO */
    IF v_emp_salary < v_sal_prom THEN
          DBMS_OUTPUT.PUT_LINE(v_emp_nom||' '||v_emp_ape||' trabaja como '||v_emp_job||' y posee un salario inferior al promedio');
/* SI EL SALARIO ES MAYOR O IGUAL AL PROMEDIO, IMPRIME EL MENSAJE DE ACUERDO AL FORMATO */
    ELSE
          DBMS_OUTPUT.PUT_LINE(v_emp_nom||' '||v_emp_ape||' trabaja como '||v_emp_job||' y posee un salario igual o superior al promedio'); 
    END IF; -- CIERRE CONDICIONAL IF
END; -- FINALIZACIÓN DEL BLOQUE

-- REQUERIMIENTO 5
DECLARE -- INICIO ZONA DECLARATIVA
/* SE DECLARAN LAS VARIABLES PARA ALMACENAR EL ID DEL EMPLEADO Y EL SUELDO DEL 
EMPLEADO, CUYOS TIPOS DE DATOS SERÁN LOS MISMOS QUE LOS CAMPOS EMPLOYEE_ID Y 
SALARY DE LA TABLA EMPLOYEES*/
v_emp_id employees.employee_id%TYPE; 
v_emp_salary employees.salary%TYPE;
BEGIN -- INICIO ZONA EJECUTABLE
/* LUEGO, A TRAVÉS DEL CICLO FOR CON UNA VARIABLE CONTROLADORA DEL CICLO i QUE
VA DEL VALOR 100 AL 120 (MISMOS VALORES DE LOS ID DE LOS EMPLEADOS A CONSULTAR),
A TRAVÉS DE LA CONSULTA SELECT, SE OBTIENE EL IDY SALARIO DEL EMPLEADO 
Y SE ALMACENA EN SUS RESPECTIVAS VARIABLES, PREVIAMENTE DECLARADAS (CLÁUSULA INTO)*/ 
FOR i IN 100 .. 120 LOOP  
    SELECT employee_id, salary
    INTO v_emp_id, v_emp_salary
    FROM employees
    WHERE employee_id = i;
/* A TRAVÉS DEL IF, SE PREGUNTA SI EL SALARIO DEL EMPLEADO ES MAYOR A 10000, 
SI ES ASÍ, IMPRIME EL MENSAJE DE ACUERDO AL FORMATO */ 
    IF v_emp_salary  > 10000  THEN
        DBMS_OUTPUT.PUT_LINE('El salario actual del empleado '||v_emp_id||' es de '||v_emp_salary||'. Es un Excelente salario');
/* SI EL SALARIO ES MAYOR O IGUAL A 9000 Y MENOR O IGUAL A 10000,
IMPRIME EL MENSAJE DE ACUERDO AL FORMATO */
    ELSIF v_emp_salary >= 9000 AND  v_emp_salary <= 10000 THEN
        DBMS_OUTPUT.PUT_LINE('El salario actual del empleado '||v_emp_id||' es de '||v_emp_salary||'. Es un Salario Normal');
-- SI EL SALARIO ES MENOR A 9000, IMPRIME EL MENSAJE DE ACUERDO AL FORMATO 
    ELSE
        DBMS_OUTPUT.PUT_LINE('El salario actual del empleado '||v_emp_id||' es de '||v_emp_salary||'. Le Deben Aumentar el Salario');
   END IF; -- CIERRE CONDICIONAL IF
END LOOP; -- CIERRE CICLO FOR
END; -- FINALIZACIÓN DEL BLOQUE

